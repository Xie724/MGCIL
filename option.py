parser.add_argument('--lamda_video', type=float, default=0.1, help='Weight for video-level contrastive loss')
# =========================================================================
# MGCIL experiment switches (0/1). DEFAULT = full MGCIL (paper config).
# To reproduce the pure MACIL-SD baseline, pass all --use_* 0 plus --grad_clip 0.
# =========================================================================
parser.add_argument('--seed', type=int, default=1888, help='random seed')
parser.add_argument('--use_cgm', type=int, default=1, help='1 = confidence-gated semi-bag mining (CGM); 0 = hard-threshold baseline pooling')
parser.add_argument('--use_uwc', type=int, default=1, help='1 = uncertainty-weighted cross-modal consistency loss (UWC)')
parser.add_argument('--use_anchor', type=int, default=1, help='1 = CLIP semantic-anchor contrastive loss (SAO)')
parser.add_argument('--use_adv', type=int, default=1, help='1 = adversarial negative construction (ANC)')
parser.add_argument('--use_vlc', type=int, default=1, help='1 = video-level contrastive loss (VLC)')
parser.add_argument('--use_gts', type=int, default=1, help='1 = Gaussian temporal smoothing at inference (GTS)')
parser.add_argument('--grad_clip', type=float, default=1.0, help='gradient clipping max norm; 0 disables')
parser.add_argument('--conf_temp', type=float, default=0.2, help='gating temperature tau_c of CGM (soft-confidence)')
parser.add_argument('--gts_sigma', type=float, default=2.0, help='Gaussian smoothing sigma at inference (GTS)')
